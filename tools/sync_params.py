#!/usr/bin/env python3
"""
================================================================================
  FOLKRACE PARAMETER SYNCHRONIZATION PIPELINE
================================================================================
  Single Source of Truth: config/vehicle_config.json
  Generates:
    1. core/vehicle_params.py                   (Webots, Pi 4, Launchers)
    2. ESP32/ESP32_Main/include/vehicle_params.h (ESP32 C++ Firmware)
================================================================================
"""

import os
import sys
import json
import math
from pathlib import Path

# Determine project repository root (supports CLI and PlatformIO SCons context)
try:
    SCRIPT_DIR = Path(__file__).resolve().parent
    REPO_ROOT = SCRIPT_DIR.parent
except NameError:
    # In PlatformIO SCons execution, __file__ is undefined
    REPO_ROOT = Path.cwd()
    SCRIPT_DIR = REPO_ROOT / "tools"

CONFIG_PATH = REPO_ROOT / "config" / "vehicle_config.json"
PY_OUT_PATH = REPO_ROOT / "core" / "vehicle_params.py"
H_OUT_PATH = REPO_ROOT / "ESP32" / "ESP32_Main" / "include" / "vehicle_params.h"


def load_config() -> dict:
    if not CONFIG_PATH.exists():
        raise FileNotFoundError(f"Configuration file not found: {CONFIG_PATH}")
    with open(CONFIG_PATH, "r", encoding="utf-8") as f:
        return json.load(f)


def compute_derived_params(cfg: dict) -> dict:
    v = cfg["vehicle"]
    d = cfg["dynamics"]
    t = cfg["timing"]

    rear_offset = float(v["rear_axle_offset_m"])
    front_offset = float(v["front_axle_offset_m"])
    wheelbase = front_offset - rear_offset

    tire_mu = float(d["tire_mu"])
    gravity_g = float(d["gravity_g"])
    a_max_base = tire_mu * gravity_g

    accel_fwd_max = float(d["accel_fwd_ratio"]) * a_max_base
    brake_decel_max = float(d["brake_decel_ratio"]) * a_max_base
    lat_accel_max = float(d["lat_accel_ratio"]) * a_max_base

    max_steer_rad = float(v["max_steering_rad"])
    r_min_turn = wheelbase / math.tan(max_steer_rad)
    v_min_cruise = math.sqrt(lat_accel_max * r_min_turn)

    ctrl_freq = float(t["control_loop_freq_hz"])
    ctrl_period_us = int(1_000_000 / ctrl_freq)
    ctrl_dt_s = 1.0 / ctrl_freq

    return {
        "wheelbase_m": wheelbase,
        "a_max_base": a_max_base,
        "accel_fwd_max": accel_fwd_max,
        "brake_decel_max": brake_decel_max,
        "lat_accel_max": lat_accel_max,
        "r_min_turn": r_min_turn,
        "v_min_cruise": v_min_cruise,
        "ctrl_period_us": ctrl_period_us,
        "ctrl_dt_s": ctrl_dt_s,
    }


