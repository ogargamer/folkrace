def sync_all():
    cfg = load_config()
    derived = compute_derived_params(cfg)

    # 1. Generate Python params
    PY_OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    py_code = generate_python(cfg, derived)
    with open(PY_OUT_PATH, "w", encoding="utf-8") as f:
        f.write(py_code)

    # 2. Generate C++ header
    H_OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    h_code = generate_c_header(cfg, derived)
    with open(H_OUT_PATH, "w", encoding="utf-8") as f:
        f.write(h_code)

    print(f"[sync_params] Synced vehicle params -> {PY_OUT_PATH.name} and {H_OUT_PATH.name}")


# PlatformIO SCons execution support
try:
    import SCons.Script  # type: ignore
    # Running inside PlatformIO SCons
    sync_all()
except (ImportError, AttributeError):
    # Standalone CLI execution
    if __name__ == "__main__":
        sync_all()
