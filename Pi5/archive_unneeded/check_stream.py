import paramiko
import sys

sys.stdout.reconfigure(encoding='utf-8')

PI_IP = "192.168.0.13"
PI_USER = "admin"
PI_PASS = "l"

def check_pi_output():
    ssh = paramiko.SSHClient()
    ssh.set_missing_host_key_policy(paramiko.AutoAddPolicy())
    ssh.connect(PI_IP, port=22, username=PI_USER, password=PI_PASS, timeout=10)

    print("======================================================================")
    print("  RUNNING LIVE MATRIX STREAM ON PI 5 DIRECTLY")
    print("======================================================================")

    stdin, stdout, stderr = ssh.exec_command("cd /home/admin/STSW-IMG042/VL53L8CX_Linux_driver_2.1.0/user/test && ./live_matrix_stream", get_pty=True)

    for line in iter(stdout.readline, ""):
        print(line, end="")

    exit_code = stdout.channel.recv_exit_status()
    print(f"\nExit Code: {exit_code}")
    ssh.close()

if __name__ == "__main__":
    check_pi_output()
